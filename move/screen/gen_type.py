"""the Move's type: Tiny5 (SIL OFL 1.1, its licence beside it) at 8 px for 128 x 64, sentence case, into
move/screen/dmk_type.h. Each glyph: its advance, then eight columns of ten rows, bit 0 the capitals' top row. Run from
the repo's root."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FILE, SIZE, TOP = "Tiny5.ttf", 8, 2                   # the file, its size, the row its capitals start on


def table(name, file, size, top):
    f = ImageFont.truetype("move/screen/" + file, size)
    rows = []
    for c in range(32, 127):
        im = Image.new("1", (14, 14), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), chr(c), font=f, fill=1)
        cols = []
        for x in range(14):
            b = 0
            for y in range(10):
                if top + y < 14 and im.getpixel((x, top + y)):
                    b |= 1 << y
            cols.append(b)
        used = max((x + 1 for x in range(14) if cols[x]), default=0)
        rows.append([3 if c == 32 else used + 1] + cols[:8])
    out = [f"static const uint16_t {name}[95][9] = {{"]
    out += ["    {" + ",".join(str(v) for v in r) + "}," for r in rows]
    return out + ["};"]


out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* generated by move/screen/gen_type.py from Tiny5 (SIL OFL 1.1): never edited by hand */",
       "/* chars 32..126: the advance, then eight columns, bit 0 the capitals' top row */"]
out += table("TYPE", FILE, SIZE, TOP)
out.append("")
Path("move/screen/dmk_type.h").write_text("\n".join(out))
