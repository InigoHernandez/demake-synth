"""The key sensing's two tables (firmware/fm1/src/sense.c: the keys' velocity, Velo's module): log2 in 1/256 and
2^-x in Q15, as CS-1's gen_tables makes them. Writes firmware/fm1/gen/sense_tables.h."""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "firmware" / "fm1" / "gen" / "sense_tables.h"


def table(name, ctype, vals, per):
    rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n"


out = ["/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/fm1/gen_sense.py: do not edit. */\n#pragma once\n",
       table("LOG2_Q8", "uint16_t", [0] + [round(256 * math.log2(x)) for x in range(1, 1024)], 16),
       table("EXP2N_Q15", "uint16_t", [round(32768 * 2 ** (-f / 256)) for f in range(256)], 8)]
OUT.write_text("".join(out))
print(OUT)
